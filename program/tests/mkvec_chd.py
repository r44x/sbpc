"""Generates tests/chd_vectors.h for tests/test_chd.c (python tests/mkvec_chd.py > tests/chd_vectors.h): raw Deflate (zlib), raw LZMA lc3/lp0/pb2 (lzma) and
hand-assembled FLAC frames. Output: C arrays on stdout."""
import lzma
import zlib


def carr(name, data):
    out = "static const uint8_t %s[%d] = {" % (name, len(data))
    for i, b in enumerate(data):
        if i % 16 == 0:
            out += "\n    "
        out += "0x%02X," % b
    return out + "\n};\n"


# plain text-ish payload with repeats (exercises literals, matches and reps)
payload = (b"SBPC test vector: Saturn Bomberman. " * 20) + bytes(range(256)) + b"\x00" * 300 + b"end"
co = zlib.compressobj(9, zlib.DEFLATED, -15)
deflated = co.compress(payload) + co.flush()
stored = zlib.compressobj(0, zlib.DEFLATED, -15)
stored_d = stored.compress(payload[:100]) + stored.flush()
lz = lzma.compress(payload, format=lzma.FORMAT_RAW,
                   filters=[{"id": lzma.FILTER_LZMA1, "lc": 3, "lp": 0, "pb": 2, "dict_size": 1 << 16}])


class Bits:
    def __init__(self):
        self.bits = []

    def put(self, v, n):
        for i in range(n - 1, -1, -1):
            self.bits.append((v >> i) & 1)

    def put_signed(self, v, n):
        self.put(v & ((1 << n) - 1), n)

    def align(self):
        while len(self.bits) % 8:
            self.bits.append(0)

    def bytes(self):
        self.align()
        out = bytearray()
        for i in range(0, len(self.bits), 8):
            b = 0
            for k in range(8):
                b = (b << 1) | self.bits[i + k]
            out.append(b)
        return bytes(out)


def rice(bw, vals, param):
    for v in vals:
        u = (v << 1) if v >= 0 else ((-v) << 1) - 1
        q, r = u >> param, u & ((1 << param) - 1)
        bw.bits.extend([0] * q)
        bw.bits.append(1)
        bw.put(r, param)


def frame(bw, block, chan, sub0, sub1, frame_no):
    bw.put(0x3FFE, 14); bw.put(0, 2)
    bw.put(7, 4)          # block size: 16-bit value follows
    bw.put(9, 4)          # 44.1 kHz
    bw.put(chan, 4)
    bw.put(4, 3)          # 16 bits
    bw.put(0, 1)
    bw.put(frame_no, 8)   # UTF-8 frame number (< 128)
    bw.put(block - 1, 16)
    bw.put(0, 8)          # CRC-8 (not checked)
    sub0(bw); sub1(bw)
    bw.align()
    bw.put(0, 16)         # CRC-16 (not checked)


N = 16
left = [1000 + 37 * i + ((i * i * 7) % 23) - 11 for i in range(N)]   # a bumpy ramp
right = [((i * 7919) % 2000) - 1000 for i in range(N)]        # noise-ish


def constant(v, bps):
    def f(bw):
        bw.put(0, 1); bw.put(0, 6); bw.put(0, 1); bw.put_signed(v, bps)
    return f


def verbatim(vals, bps):
    def f(bw):
        bw.put(0, 1); bw.put(1, 6); bw.put(0, 1)
        for v in vals:
            bw.put_signed(v, bps)
    return f


def fixed2(vals, bps, param):
    def f(bw):
        bw.put(0, 1); bw.put(8 + 2, 6); bw.put(0, 1)
        bw.put_signed(vals[0], bps); bw.put_signed(vals[1], bps)
        res = [vals[i] - 2 * vals[i - 1] + vals[i - 2] for i in range(2, len(vals))]
        bw.put(0, 2); bw.put(0, 4); bw.put(param, 4)
        rice(bw, res, param)
    return f


bw = Bits()
# frame 0: independent stereo: left fixed order 2 (a ramp: residual 0), right verbatim
frame(bw, N, 1, fixed2(left, 16, 2), verbatim(right, 16), 0)
# frame 1: left/side: left constant 500, side = left - right (17 bits) verbatim
right2 = [500 - ((i * 13) % 300) for i in range(N)]
frame(bw, N, 8, constant(500, 16), verbatim([500 - r for r in right2], 17), 1)
# frame 2: mid/side
l3 = [(-3000 + 400 * i) for i in range(N)]
r3 = [(2000 - 150 * i + ((i * 5) % 9) * 3) for i in range(N)]
mid = [(a + b) >> 1 for a, b in zip(l3, r3)]
side = [a - b for a, b in zip(l3, r3)]
frame(bw, N, 10, verbatim(mid, 16), fixed2(side, 17, 5), 2)
flac = bw.bytes()
expect = []
for a, b in zip(left, right):
    expect += [a, b]
for b in right2:
    expect += [500, b]
for a, b in zip(l3, r3):
    expect += [a, b]

