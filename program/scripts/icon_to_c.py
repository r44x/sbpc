"""Turns the program icon (program/res/icon.png, the user's own pixel art) into what the build uses.
Standard library only.

    python program/scripts/icon_to_c.py program/res/icon.png program/res [sbpc.png]

Writes:
  sbpc.ico       Windows icon (16, 32, 48 and 256 pixels, scaled up by whole steps, nearest neighbour),
                 built into sbpc.exe and sbpc-cli.exe by res/sbpc.rc.
  icon_rgba.h    the icon as RGBA bytes, set as the window icon at run time (all platforms).
The icon is padded to a square first (centred, transparent)."""
import struct
import sys
import zlib


def load_png(path):
    d = open(path, 'rb').read()
    assert d[:8] == b'\x89PNG\r\n\x1a\n', 'not a PNG'
    p, idat, plte, trns = 8, b'', None, None
    while p < len(d):
        ln, typ = struct.unpack('>I4s', d[p:p + 8])
        body = d[p + 8:p + 8 + ln]
        if typ == b'IHDR':
            w, h, bd, ct, _, _, il = struct.unpack('>IIBBBBB', body)
        elif typ == b'PLTE':
            plte = body
        elif typ == b'tRNS':
            trns = body
        elif typ == b'IDAT':
            idat += body
        p += 12 + ln
    assert bd == 8 and il == 0, 'only 8-bit, non-interlaced PNGs'
    bpp = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ct]
    raw = zlib.decompress(idat)
    stride = w * bpp
    rows, prev, q = [], bytearray(stride), 0
    for _ in range(h):
        f = raw[q]; q += 1
        cur = bytearray(raw[q:q + stride]); q += stride
        for i in range(stride):
            a = cur[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1: cur[i] = (cur[i] + a) & 255
            elif f == 2: cur[i] = (cur[i] + b) & 255
            elif f == 3: cur[i] = (cur[i] + (a + b) // 2) & 255
            elif f == 4:
                pp = a + b - c; pa, pb, pc = abs(pp - a), abs(pp - b), abs(pp - c)
                cur[i] = (cur[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(cur)); prev = cur
    px = []
    for r in rows:
        for x in range(w):
            if ct == 6: px.append(tuple(r[4 * x:4 * x + 4]))
            elif ct == 2: px.append(tuple(r[3 * x:3 * x + 3]) + (255,))
            elif ct == 4: px.append((r[2 * x],) * 3 + (r[2 * x + 1],))
            elif ct == 0: px.append((r[x],) * 3 + (255,))
            else:
                i = r[x]
                a = trns[i] if trns and i < len(trns) else 255
                px.append(tuple(plte[3 * i:3 * i + 3]) + (a,))
    return w, h, px


def square(w, h, px):
    n = max(w, h)
    ox, oy = (n - w) // 2, (n - h) // 2
    out = [(0, 0, 0, 0)] * (n * n)
    for y in range(h):
        for x in range(w):
            out[(y + oy) * n + x + ox] = px[y * w + x]
    return n, out


def scaled(n, px, size):
    """Nearest neighbour to size x size, centred when size isn't a whole multiple."""
    k = max(1, size // n)
    off = (size - n * k) // 2
    out = [(0, 0, 0, 0)] * (size * size)
    for y in range(n * k):
        for x in range(n * k):
            out[(y + off) * size + x + off] = px[(y // k) * n + x // k]
    return out


def dib(size, px):
    """32-bit BMP for an ICO entry: header with double height, bottom-up BGRA rows, then the AND mask."""
    hdr = struct.pack('<IiiHHIIiiII', 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    body = b''.join(bytes((r[2], r[1], r[0], r[3]))
                    for y in range(size - 1, -1, -1) for r in px[y * size:(y + 1) * size])
    mask_stride = ((size + 31) // 32) * 4
    mask = bytearray()
    for y in range(size - 1, -1, -1):
        row = bytearray(mask_stride)
        for x in range(size):
            if px[y * size + x][3] == 0:
                row[x // 8] |= 0x80 >> (x % 8)
        mask += row
    return hdr + body + bytes(mask)


def png_bytes(size, px):
    raw = b''.join(b'\0' + bytes(c for p in px[y * size:(y + 1) * size] for c in p) for y in range(size))
    def ch(t, b): return struct.pack('>I', len(b)) + t + b + struct.pack('>I', zlib.crc32(t + b) & 0xffffffff)
    return (b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0)) +
            ch(b'IDAT', zlib.compress(raw, 9)) + ch(b'IEND', b''))


def main():
    src, out = sys.argv[1], sys.argv[2]
    n, px = square(*load_png(src))
    sizes = [16, 32, 48, 256]
    images = [png_bytes(s, scaled(n, px, s)) if s == 256 else dib(s, scaled(n, px, s)) for s in sizes]
    ico = struct.pack('<HHH', 0, 1, len(sizes))
    off = 6 + 16 * len(sizes)
    for s, img in zip(sizes, images):
        ico += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(img), off)
        off += len(img)
    open(out + '/sbpc.ico', 'wb').write(ico + b''.join(images))

    lines = ['/* Generated by program/scripts/icon_to_c.py from res/icon.png (the user\'s own art). Do not edit. */',
             '#ifndef SBPC_ICON_RGBA_H', '#define SBPC_ICON_RGBA_H', '',
             '#define SBPC_ICON_SIZE %d' % n,
             'static const unsigned char sbpc_icon_rgba[SBPC_ICON_SIZE * SBPC_ICON_SIZE * 4] = {']
    flat = [c for p in px for c in p]
    for i in range(0, len(flat), 16):
        lines.append('    ' + ', '.join('0x%02X' % c for c in flat[i:i + 16]) + ',')
    lines += ['};', '', '#endif', '']
    open(out + '/icon_rgba.h', 'w', newline='\n').write('\n'.join(lines))
    print('wrote %s/sbpc.ico and %s/icon_rgba.h (%dx%d)' % (out, out, n, n))
    if len(sys.argv) > 3:   # a 256x256 PNG for Linux packages (the release workflow's AppImage)
        open(sys.argv[3], 'wb').write(png_bytes(256, scaled(n, px, 256)))
        print('wrote %s (256x256)' % sys.argv[3])


if __name__ == '__main__':
    main()
